#!/usr/bin/env python3
"""
Update dependency versions table from pyproject.toml
"""
import re
from pathlib import Path


def parse_dependencies_from_pyproject():
    """Parse dependencies from pyproject.toml manually."""
    project_root = Path(__file__).parent.parent
    pyproject_path = project_root / "pyproject.toml"
    
    with open(pyproject_path, "r", encoding="utf-8") as f:
        content = f.read()
    
    deps = {}
    
    # Extract dependencies from the [project] section
    in_dependencies = False
    in_dev_dependencies = False
    
    for line in content.split('\n'):
        line = line.strip()
        
        if line == 'dependencies = [':
            in_dependencies = True
            continue
        elif line == ']' and in_dependencies:
            in_dependencies = False
            continue
        elif 'dev = [' in line:
            in_dev_dependencies = True
            continue
        elif line == ']' and in_dev_dependencies:
            in_dev_dependencies = False
            continue
            
        if (in_dependencies or in_dev_dependencies) and line.startswith('"') and line.endswith('",'):
            # Extract dependency string
            dep = line[1:-2]  # Remove quotes and comma
            
            # Extract package name and version spec
            match = re.match(r"^([^>=<~!]+)([>=<~!].*)?", dep)
            if match:
                name = match.group(1).strip()
                version_spec = match.group(2) or ""
                deps[name] = f"{name}{version_spec}"
    
    return deps

def main():
    """Update the dependency versions table."""
    project_root = Path(__file__).parent.parent
    target_path = project_root / "src" / "femtotransformers" / "dependency_versions_table.py"
    
    # Parse dependencies
    deps = parse_dependencies_from_pyproject()
    
    # Generate the content
    entries = "\n".join([f'    "{k}": "{v}",' for k, v in sorted(deps.items())])
    content = [
        "# THIS FILE HAS BEEN AUTOGENERATED. To update:",
        "# 1. modify the dependencies in pyproject.toml",
        "# 2. run `python utils/update_dependency_table.py`",
        "deps = {",
        entries,
        "}",
        "",
    ]
    
    print(f"Updating {target_path}")
    with open(target_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(content))
    
    print("Dependency table updated successfully!")


if __name__ == "__main__":
    main()
